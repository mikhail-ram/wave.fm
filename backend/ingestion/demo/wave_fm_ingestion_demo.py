def load_mulan(device: str = "cuda"):
    device = device if torch.cuda.is_available() else "cpu"
    mulan = MuQMuLan.from_pretrained("OpenMuQ/MuQ-MuLan-large")  # downloads checkpoint from HF if necessary
    mulan = mulan.to(device).eval()
    return mulan, device

# Run a batch of waveforms (numpy arrays of shape [SAMPLES_PER_CHUNK]) through MuQ-MuLan
# returns numpy array [batch, D]
def mulan_infer_batch(mulan, device, waveforms: List[np.ndarray]) -> np.ndarray:
    # stack, convert to torch.float32 tensor
    batch = np.stack(waveforms, axis=0)
    batch_t = torch.from_numpy(batch).to(device=device, dtype=torch.float32)
    with torch.no_grad():
        emb_t = mulan(wavs=batch_t)  # per example usage
    # ensure CPU numpy
    return emb_t.cpu().numpy()

# L2-normalize (optional)
def l2_normalize(vec: np.ndarray, eps: float = 1e-12) -> np.ndarray:
    norm = np.linalg.norm(vec)
    if norm < eps:
        return vec
    return vec / norm

# Mean-pool list of embeddings
def mean_pool_embeddings(embs_list: List[np.ndarray], l2_norm: bool = False) -> np.ndarray:
    if not embs_list:
      return np.zeros((1,), dtype=np.float32)
    stacked = np.stack(embs_list, axis=0)
    mean_vec = np.mean(stacked, axis=0)
    if l2_norm:
        mean_vec = l2_normalize(mean_vec)
    return mean_vec

