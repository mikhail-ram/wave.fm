import types

def patched_forward(self, x=None, raw_texts=None, mask=None, return_all_layers=False, return_mean=True):
    """
    Monkey-patched forward to handle both raw_texts and already-tokenized input.
    """
    assert (x is not None) ^ (raw_texts is not None), "Provide only one of x or raw_texts"
    with torch.no_grad():
        if raw_texts is not None:
            # Standard path: let model handle tokenization
            inputs = self.tokenizer(
                raw_texts,
                return_tensors='pt',
                padding='max_length',
                truncation=True,
                max_length=self.max_seq_len
            )
            inputs = inputs.to(self.device)
            if mask is not None:
                inputs['attention_mask'] = mask
            outputs = self.pred_pretrained_model_hidden(**inputs)
        elif x is not None:
            # Already-tokenized path
            inputs = {'input_ids': x}
            if mask is not None:
                inputs['attention_mask'] = mask
            outputs = self.pred_pretrained_model_hidden(**inputs)
        else:
            raise ValueError("Either x or raw_texts must be provided.")

    outputs = self.proj(outputs)
    outputs, layer_results = self.transformer(outputs, return_all_layers=True)
    if return_mean:
        outputs = outputs.mean(dim=-2)
    if return_all_layers:
        return outputs, layer_results
    return outputs

