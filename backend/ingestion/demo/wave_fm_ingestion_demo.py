# ---------- utility ----------------
def normalize_text(s: str) -> str:
    """Normalize for reliable substring search: unicode NFKD, lowercase, collapse whitespace."""
    if s is None:
        return ""
    s = unicodedata.normalize("NFKD", s)
    s = s.lower()
    s = re.sub(r"\s+", " ", s).strip()
    return s

