# ---------- Lexical FTS (pure substring search + simple heuristic ranking) ----------
def lexical_fts_best_match(client: chromadb.Client,
                           query: str,
                           lyrics_collection_name: str = "lyrics_embeddings",
                           limit_candidates: int = 100,
                           return_k: int = 1) -> List[Dict[str, Any]]:
    """
    Pure lexical FTS (no model calls). Returns top `return_k` matches ordered by a small heuristic:
    - exact title / exact artist > startswith > contains > occurrences in lyrics
    Each candidate: { id, score, title, artist, snippet, metadata }
    """
    if not query or not query.strip():
        return []

    q_norm = normalize_text(query)
    col = client.get_collection(name=lyrics_collection_name)

    # get candidates whose normalized document contains the normalized query
    res = col.get(where_document={"$contains": q_norm}, limit=limit_candidates, include=["metadatas","documents"])
    ids = res.get("ids", [])
    metadatas = res.get("metadatas", [])
    documents = res.get("documents", [])

    candidates = []
    for i, sid in enumerate(ids):
        md = metadatas[i] if i < len(metadatas) else {}
        doc = documents[i] if i < len(documents) else ""
        title = md.get("title","")
        artist = md.get("artist","")

        t_norm = normalize_text(title)
        a_norm = normalize_text(artist)
        d_norm = doc or ""

        score = 0
        # title signals (heaviest)
        if t_norm == q_norm:
            score += 1000
        elif t_norm.startswith(q_norm):
            score += 700
        elif q_norm in t_norm:
            score += 500

        # artist signals
        if a_norm == q_norm:
            score += 600
        elif a_norm.startswith(q_norm):
            score += 400
        elif q_norm in a_norm:
            score += 200

        # lyrics occurrences give signal but are weaker
        occ = d_norm.count(q_norm)
        score += min(occ, 10) * 20

        # token overlap bonus
        q_tokens = set(q_norm.split())
        score += len(q_tokens.intersection(set(t_norm.split()))) * 10
        score += len(q_tokens.intersection(set(a_norm.split()))) * 6

        # snippet: show surrounding text for UI if found in document
        snippet = None
        idx = d_norm.find(q_norm)
        if idx != -1:
            start = max(0, idx - 120)
            end = min(len(d_norm), idx + len(q_norm) + 120)
            snippet = d_norm[start:end]
        else:
            snippet = title or artist

        candidates.append({
            "id": sid,
            "score": score,
            "title": title,
            "artist": artist,
            "snippet": snippet,
            "metadata": md
        })

    # sort desc: higher score = better
    candidates.sort(key=lambda x: x["score"], reverse=True)
    return candidates[:return_k]

