def interpolate_songs(client,
                      source_song_id: str,
                      destination_song_id: str,
                      k: int,
                      alpha: float = 0.5,
                      limit_candidates: int = 50,
                      lyrics_collection_name: str = "lyrics_embeddings",
                      audio_collection_name: str = "audio_embeddings"):
    """
    Interpolate between source and destination songs, returning k songs in between.
    Uses weighted multi-modal embeddings and linear interpolation in embedding space.
    """
    # --- Fetch merged embeddings for source and destination ---
    def get_merged_embedding(song_id):
        lyrics_col = client.get_collection(name=lyrics_collection_name)
        audio_col  = client.get_collection(name=audio_collection_name)
        lyrics_res = lyrics_col.get(ids=[song_id], include=["embeddings", "metadatas"])
        audio_res  = audio_col.get(ids=[song_id], include=["embeddings", "metadatas"])
        lyrics_emb = np.array(lyrics_res["embeddings"][0]) if len(lyrics_res.get("embeddings", [])) > 0 else None
        audio_emb  = np.array(audio_res["embeddings"][0])  if len(audio_res.get("embeddings", [])) > 0 else None

        if lyrics_emb is None and audio_emb is None:
            raise ValueError(f"Both modalities missing for {song_id}")

        # Fallback for alpha if requested modality missing
        if alpha >= 0.5 and audio_emb is None:
            print(f"Warning: Audio missing for {song_id}, using lyrics instead.")
            merged = lyrics_emb
        elif alpha < 0.5 and lyrics_emb is None:
            print(f"Warning: Lyrics missing for {song_id}, using audio instead.")
            merged = audio_emb
        else:
            # Compute weighted embedding
            merged = (alpha * audio_emb if audio_emb is not None else 0.0) + \
                     ((1-alpha) * lyrics_emb if lyrics_emb is not None else 0.0)

        # Normalize
        norm = np.linalg.norm(merged)
        if norm == 0:
            raise ValueError(f"Song {song_id} has zero norm embedding.")
        return merged / norm

    source_emb = get_merged_embedding(source_song_id)
    dest_emb   = get_merged_embedding(destination_song_id)

    # Check if source and destination are identical
    if np.allclose(source_emb, dest_emb):
        raise ValueError("Source and destination embeddings are identical; cannot interpolate.")

    # --- Compute unit step vector ---
    delta = dest_emb - source_emb
    step_vector = delta / (k + 1)

    # --- Interpolation loop ---
    used_ids = set([source_song_id, destination_song_id])
    interpolated_songs = []

    # Add source song
    interpolated_songs.append({"id": source_song_id, "embedding": source_emb})

    for i in range(1, k + 1):
        query_emb = source_emb + i * step_vector
        # Check for zero vector
        if np.linalg.norm(query_emb) == 0:
            print(f"Warning: Step {i} produced zero vector; skipping.")
            continue

        # Find nearest song not in used_ids
        result = weighted_modal_search_interpolate(
            client,
            query_emb=query_emb,
            skip_ids=list(used_ids),
            alpha=alpha,
            limit_candidates=limit_candidates,
            return_k=1,
            lyrics_collection_name=lyrics_collection_name,
            audio_collection_name=audio_collection_name
        )

        if result:
            interpolated_songs.append(result[0])
            used_ids.add(result[0]["id"])
        else:
            print(f"Warning: No candidate found for step {i}.")

    # Add destination song
    interpolated_songs.append({"id": destination_song_id, "embedding": dest_emb})

    return interpolated_songs

