@dataclass
class SongData:
    """A lean, centralized data structure for tracking the final state of a song."""
    # Core identifiers from the manifest
    title: str
    artist: str

    # The stable, unique ID for tracking this song
    song_id: Optional[str] = None

    # Flags to control the processing pipeline
    process_audio: bool = False
    process_lyrics: bool = False

    # Final state and data
    audio_status: str = "pending"
    lyrics_status: str = "pending"
    audio_embedding: Optional[np.ndarray] = None
    lyrics_text: Optional[str] = None
    lyrics_embedding: Optional[np.ndarray] = None
    duration: Optional[float] = None
    num_chunks: Optional[int] = None
    failure_reason: Optional[str] = None

    def to_song_record(self) -> Dict[str, Any]:
        """Converts the final data to a dictionary for songs.jsonl."""
        audio_emb_list = self.audio_embedding.astype(float).tolist() if self.audio_embedding is not None else None
        lyrics_emb_list = self.lyrics_embedding.astype(float).tolist() if self.lyrics_embedding is not None else None
        return {
            "song_id": self.song_id,
            "title": self.title,
            "artist": self.artist,
            "duration": self.duration,
            "num_chunks": self.num_chunks,
            "audio_embedding": audio_emb_list,
            "lyrics": self.lyrics_text,
            "lyrics_embedding": lyrics_emb_list,
            "processed_at": datetime.datetime.now(datetime.timezone.utc).isoformat(),
        }

def _normalize_string(s: str) -> str:
    """Normalizes a string for use in a fallback ID."""
    s = s.lower()
    s = re.sub(r"[^a-z0-9]+", "-", s)
    return s.strip("-")

def identify_songs_to_process(
    manifest: List[Dict],
    processed_statuses: Dict[str, Dict[str, str]]
) -> List[SongData]:
    """Identifies songs that need processing and creates a stable ID for them."""
    songs_to_process = []
    print("Identifying songs for processing...")
    for entry in tqdm(manifest, desc="Checking manifest"):
        title = entry.get("title")
        artist = entry.get("artist")
        song = SongData(title=title, artist=artist)

        # 1. Attempt to find on YouTube to get the primary ID
        yt_meta = youtube_search_top(title, artist)

        if yt_meta and yt_meta.get("id"):
            song.song_id = f"yt:{yt_meta['id']}"
        else:
            # 2. Create a stable fallback ID if YouTube search fails
            normalized_id = f"{_normalize_string(artist)}-{_normalize_string(title)}"
            song.song_id = f"local:{normalized_id}"
            # As requested, only audio processing is impossible without a source
            song.audio_status = "failed"
            song.failure_reason = "youtube_no_result"
            print(f"[Info] No YouTube result for '{title}'. Will attempt lyrics processing with ID {song.song_id}")

        # 3. Check status and decide what to process
        status = processed_statuses.get(song.song_id)
        if status and status.get("audio_status") == "done" and status.get("lyrics_status") == "done":
            continue

        # Determine if audio needs processing (it must not have failed from the start)
        song.process_audio = (song.audio_status != "failed") and not (status and status.get("audio_status") == "done")

        # Determine if lyrics need processing
        song.process_lyrics = not (status and status.get("lyrics_status") == "done")

        if song.process_audio or song.process_lyrics:
            songs_to_process.append(song)

    return songs_to_process

def download_audio(songs: List[SongData], tmp_dir: Path, concurrency: int) -> Dict[str, Path]:
    """Downloads audio files and returns a map of song_id -> wav_path."""
    songs_to_download = [s for s in songs if s.process_audio]
    if not songs_to_download:
        return {}

    song_to_wav_path = {}

    def _dl_task(song: SongData):
        try:
            video_id = song.song_id.split(":")[-1]
            wav_path = download_video_to_wav(video_id, tmp_dir, retries=RETRY_DOWNLOADS)
            return song, wav_path, None
        except Exception as e:
            return song, None, e

    with ThreadPoolExecutor(max_workers=concurrency) as ex:
        futures = {ex.submit(_dl_task, song): song for song in songs_to_download}
        for fut in tqdm(as_completed(futures), total=len(futures), desc="Downloading"):
            song, wav_path, error = fut.result()
            if error:
                song.audio_status = "failed"
                song.failure_reason = song.failure_reason or f"download_failed: {error}"
            else:
                song_to_wav_path[song.song_id] = wav_path

    return song_to_wav_path

def compute_audio_embeddings(mulan, device, songs: List[SongData], song_to_wav_path: Dict[str, Path], window_size: int, l2_norm: bool):
    """Computes audio embeddings for successfully downloaded songs."""
    songs_with_audio = [s for s in songs if s.song_id in song_to_wav_path]
    if not songs_with_audio:
        return

    all_chunks = []

    # 1. Load audio and create a flat list of all chunks
    for song in songs_with_audio:
        wav_path = song_to_wav_path[song.song_id]
        try:
            chunks = load_wav_and_chunk(wav_path, song.song_id, song.title, song.artist)
            song.duration = librosa.get_duration(path=wav_path)
            song.num_chunks = len(chunks)
            all_chunks.extend(chunks)
        except Exception as e:
            song.audio_status = "failed"
            song.failure_reason = f"chunking_failed: {e}"

    # 2. Process all chunks in batches for efficiency
    song_embeddings_map = {s.song_id: [] for s in songs_with_audio}
    for i in tqdm(range(0, len(all_chunks), window_size), desc="Audio Embedding"):
        batch_meta = all_chunks[i:i + window_size]
        waveforms = [m["waveform"] for m in batch_meta]
        emb_batch = mulan_infer_batch(mulan, device, waveforms)
        for j, meta in enumerate(batch_meta):
            song_embeddings_map[meta["song_id"]].append(l2_normalize(emb_batch[j]))

    # 3. Pool embeddings and update the SongData objects
    for song in songs_with_audio:
        if song.audio_status != "failed":
            embs = song_embeddings_map.get(song.song_id)
            if embs:
                song.audio_embedding = mean_pool_embeddings(embs, l2_norm=l2_norm)
                song.audio_status = "done"
            else:
                song.audio_status = "failed"
                song.failure_reason = song.failure_reason or "no_embeddings_generated"

def run_ingestion_pipeline(
    manifest_path: Path = MANIFEST_PATH,
    processed_path: Path = PROCESSED_PATH,
    songs_path: Path = SONGS_PATH,
    k: int = DEFAULT_K,
    window_size: int = WINDOW_SIZE,
    download_concurrency: int = DOWNLOAD_CONCURRENCY,
    tmp_root: Path = TMP_ROOT,
    l2_norm: bool = True,
):
    """
    Process the manifest in batches of size `k`. For each batch:
      - create a per-batch tmp dir
      - download audio -> compute audio embeddings -> compute lyrics embeddings
      - save results and cleanup wav files for that batch
    The model (mulan) is loaded once and reused across batches.
    """
    tmp_root.mkdir(parents=True, exist_ok=True)

    # Load model once
    mulan, device = load_mulan()
    print(f"Model loaded on {device}.")
    tokenizer = XLMRobertaTokenizer.from_pretrained("xlm-roberta-base")
    print("XLMRobertaTokenizer loaded.")

    # Monkey-patch for TextTransformerPretrained to handle forward properly
    text_transformer = mulan.mulan.text  # Should be a TextTransformerPretrained instance
    text_transformer.forward = types.MethodType(patched_forward, text_transformer)

    # Read manifest and prepare batches
    full_manifest = read_jsonl(manifest_path)
    if not full_manifest:
        print("Manifest is empty.")
        return

    total = len(full_manifest)
    batches = (total + k - 1) // k  # ceil division

    for batch_idx in tqdm(range(batches), desc="Processing batches", unit="batch"):
        start = batch_idx * k
        end = min(start + k, total)
        batch_manifest = full_manifest[start:end]
        print(f"\nBatch {batch_idx + 1}/{batches} — items {start}:{end} (count={len(batch_manifest)})")

        # Reload processed statuses to skip already-processed items
        processed_statuses = load_processed_statuses(processed_path)
        songs_to_process = identify_songs_to_process(batch_manifest, processed_statuses)

        if not songs_to_process:
            print(f"Batch {batch_idx + 1}: no songs to process (all already done).")
            continue

        batch_tmp = tmp_root / f"job_{batch_idx}_{int(time.time())}"
        batch_tmp.mkdir(parents=True, exist_ok=True)

        try:
            # song_to_wav_path: Dict[str, Path]
            song_to_wav_path = download_audio(songs_to_process, batch_tmp, download_concurrency)

            compute_audio_embeddings(mulan, device, songs_to_process, song_to_wav_path, window_size, l2_norm)
            compute_lyrics_embeddings(mulan, device, tokenizer, songs_to_process)

            wav_paths_to_clean: List[Path] = list(song_to_wav_path.values())
            save_results_and_cleanup(songs_to_process, songs_path, processed_path, wav_paths_to_clean)

        except Exception as e:
            print(f"[batch_error] batch_idx={batch_idx} exception={e}")
        finally:
            try:
                if batch_tmp.exists():
                    if not any(batch_tmp.iterdir()):
                        batch_tmp.rmdir()
                    else:
                        print(f"Batch tmp dir not empty, left at: {batch_tmp}")
            except Exception as cleanup_err:
                print(f"[tmpdir_cleanup_warning] {batch_tmp} -> {cleanup_err}")

    print("Ingestion pipeline finished.")

