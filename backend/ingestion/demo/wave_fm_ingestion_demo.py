def find_most_dissimilar_songs(audio_col):
    """
    Finds the two most dissimilar songs in the audio collection.
    Assumes embeddings are L2-normalized.
    """
    # fetch all audio embeddings and IDs
    all_data = audio_col.get(include=["embeddings"])
    ids = all_data["ids"]
    embeddings = np.array(all_data["embeddings"])  # shape: (num_songs, 512)

    # initialize
    min_sim = float("inf")
    song_pair = (None, None)

    # brute force pairwise comparison
    for i, j in combinations(range(len(ids)), 2):
        sim = np.dot(embeddings[i], embeddings[j])  # cosine similarity
        if sim < min_sim:
            min_sim = sim
            song_pair = (ids[i], ids[j])

    print(f"Most dissimilar songs: {song_pair} with similarity {min_sim:.4f}")
    return song_pair, min_sim

