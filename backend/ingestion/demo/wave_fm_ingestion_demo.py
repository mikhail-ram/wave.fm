def get_lyrics(
    title: str,
    artist: str,
) -> Optional[str]:
    """
    Search LRCLIB /api/search for the given title and artist and return the plainLyrics
    of the best-matching result. If plainLyrics is missing but syncedLyrics exists,
    a plain-text version is returned by stripping timestamp tags.

    Returns:
      - plain lyrics string if found
      - None if no match or no lyrics found (unless raise_on_missing True, then raises)
    """
    url = "https://lrclib.net/api/search"

    params = {
        "track_name": title,
        "artist_name": artist,
    }
    headers = {
        "User-Agent": "lrclib-client/0.1 (wave.fm)"
    }

    resp = requests.get(url, params=params, headers=headers, timeout=10)
    time.sleep(0.1 + random.random() * 0.1) # Polite delay to prevent overloading API
    resp.raise_for_status()
    results = resp.json()

    if not isinstance(results, list) or len(results) == 0:
        return None

    best = results[0]
    lyrics = best.get("plainLyrics")
    if lyrics:
        return clean_lyrics(lyrics)

    # fallback: if syncedLyrics exists, strip timestamps like [00:17.12] to form plain text
    lyrics = best.get("syncedLyrics")
    if lyrics:
        lyrics = re.sub(r"\[\d{2}:\d{2}(?:\.\d{1,3})?\]\s*", "", lyrics).strip()
        if lyrics:
            return clean_lyrics(lyrics)

    return None

