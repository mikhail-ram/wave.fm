def custom_truncate_tokenize(tokenizer, text, max_length=512):
    encoded = tokenizer(
        text,
        padding='max_length',
        truncation=True,
        max_length=max_length,
        return_tensors='pt'
    )
    return encoded['input_ids'], encoded['attention_mask']

def compute_lyrics_embeddings(mulan, device, tokenizer, songs_batch: List[SongData]):
    lyrics_texts = []
    valid_indices = []

    # Step 1: Gather lyrics and handle per-song errors
    for idx, song in enumerate(songs_batch):
        try:
            lyrics = get_lyrics(song.title, song.artist)
            if lyrics:
                lyrics_texts.append(lyrics)
                valid_indices.append(idx)
                song.lyrics_text = lyrics  # Store for record
            else:
                song.lyrics_status = "failed"
                song.failure_reason = "lyrics_not_found"
        except Exception as e:
            song.lyrics_status = "failed"
            song.failure_reason = f"lyrics_fetch_failed: {str(e)}"

    if not lyrics_texts:
        return  # Nothing to process

    # Step 2: Batch tokenize and embed with error catch
    try:
        input_ids, attention_mask = custom_truncate_tokenize(tokenizer, lyrics_texts, max_length=512)
        input_ids = input_ids.to(device)
        attention_mask = attention_mask.to(device)

        with torch.no_grad():
            text_embeds, _ = mulan.mulan.text(x=input_ids, mask=attention_mask, return_all_layers=True)
            text_latents = mulan.mulan.text_to_latents(text_embeds)
            emb_output = mulan.mulan._norm_latents(text_latents)

        # Step 3: Assign embeddings back, with optional per-song try/except
        for i, idx in enumerate(valid_indices):
            try:
                emb_np = emb_output[i].cpu().numpy()
                songs_batch[idx].lyrics_embedding = l2_normalize(emb_np)
                songs_batch[idx].lyrics_status = "done"
            except Exception as e:
                songs_batch[idx].lyrics_status = "failed"
                songs_batch[idx].failure_reason = f"embedding_assignment_failed: {str(e)}"

    except Exception as e:
        # If the batch model/tokenizer fails, mark all as failed
        for idx in valid_indices:
            songs_batch[idx].lyrics_status = "failed"
            songs_batch[idx].failure_reason = f"batch_embedding_failed: {str(e)}"

