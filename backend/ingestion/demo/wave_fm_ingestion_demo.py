# Use yt_dlp to search top metadata-only result (no download).
# returns dict {id,title,duration,webpage_url} or None
def youtube_search_top(title: str, artist: str, timeout: int = 30) -> Optional[Dict]:
    q = f"{title} - {artist}"
    ydl_opts = {
        "quiet": True,
        "skip_download": True,
        "noplaylist": True,
        # extract only the first result of a search ('ytsearch1:')
        # we'll call extract_info with the 'ytsearch1:' prefix below
    }
    try:
        with YoutubeDL(ydl_opts) as ydl:
            info = ydl.extract_info(f"ytsearch1:{q}", download=False)
            # yt-dlp returns a dictionary with 'entries' when searching
            entry = None
            if info is None:
                return None
            if "entries" in info:
                entries = info.get("entries", [])
                if not entries:
                    return None
                entry = entries[0]
            else:
                entry = info
            if not entry:
                return None
            # return normalized metadata
            return {
                "id": entry.get("id"),
                "title": entry.get("title"),
                "duration": entry.get("duration"),
                "webpage_url": entry.get("webpage_url")
            }
    except Exception as e:
        # treat as no result for robust behavior; caller may log the exception in reason
        return None

import subprocess
from pathlib import Path

def convert_to_wav(input_path: Path, output_path: Path, sr=24000):
    cmd = [
        "ffmpeg",
        "-y",  # overwrite if exists
        "-i", str(input_path),
        "-ar", str(sr),
        "-ac", "1",
        "-c:a", "pcm_f32le",  # use 32-bit float PCM
        str(output_path)
    ]
    subprocess.run(cmd, check=True)
    return output_path

# Download a specific video id and transcode to 24 kHz float32 mono WAV.
# Returns absolute path to WAV on success, raises on failure.
def download_video_to_wav(video_id: str, out_dir: Path, retries:int = RETRY_DOWNLOADS) -> str:
    out_dir.mkdir(parents=True, exist_ok=True)
    out_template = str(out_dir / f"{video_id}.%(ext)s")
    url = f"https://www.youtube.com/watch?v={video_id}"
    ydl_opts = {
        "format": "bestaudio/best",
        "outtmpl": out_template,
        "quiet": True,
        #"verbose": True,
        "noplaylist": True,
        # do not write metadata files
        "writethumbnail": False,
        "cookies": "/content/cookies.txt", # IMPORTANT: YT-DLP needs this to download videos for some reason
    }

    last_exc = None
    for attempt in range(1, retries+2):  # retries attempts + initial
        try:
            with YoutubeDL(ydl_opts) as ydl:
                ydl.download([url])

            # Convert manually
            webm_path = out_dir / f"{video_id}.webm"
            wav_path = out_dir / f"{video_id}.wav"
            convert_to_wav(webm_path, wav_path)


            if wav_path.exists():
                return wav_path
            else:
                raise RuntimeError(f"ffmpeg output not found at {wav_path}")
        except Exception as e:
            last_exc = e
            if attempt <= retries:
                # brief backoff
                time.sleep(1.0 * attempt)
                continue
            else:
                raise last_exc

"""## Chunk WAV"""

# Load a wav file (assumed 24k float32 mono), split into 30s chunks, pad last chunk with zeros.
# Returns list of chunk dicts: {song_id, title, artist, chunk_idx, start_time, waveform(np.float32)}
def load_wav_and_chunk(wav_path: str, song_id: str, title: str, artist: str) -> List[Dict]:
    wav, sr = librosa.load(wav_path, sr=SR, mono=True)  # returns float32
    T = wav.shape[0]
    chunks = []
    chunks_count = math.ceil(T / SAMPLES_PER_CHUNK)
    for chunk_idx in range(chunks_count):
        start = chunk_idx * SAMPLES_PER_CHUNK
        end = min(start + SAMPLES_PER_CHUNK, T)
        chunk = wav[start:end]
        if chunk.shape[0] < SAMPLES_PER_CHUNK:
            # pad with zeros to exactly SAMPLES_PER_CHUNK
            pad_len = SAMPLES_PER_CHUNK - chunk.shape[0]
            chunk = np.pad(chunk, (0, pad_len), mode="constant").astype(np.float32)
        else:
            chunk = chunk.astype(np.float32)
        chunks.append({
            "song_id": song_id,
            "title": title,
            "artist": artist,
            "chunk_idx": chunk_idx,
            "start_time": start / SR,
            "waveform": chunk
        })
    return chunks

