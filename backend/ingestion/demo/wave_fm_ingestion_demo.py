import numpy as np

def weighted_modal_search(client,
                          song_id: str,
                          alpha: float = 0.5,
                          limit_candidates: int = 50,
                          return_k: int = 10,
                          lyrics_collection_name: str = "lyrics_embeddings",
                          audio_collection_name: str = "audio_embeddings"):
    """
    Weighted multi-modal search for songs given a song_id.
    alpha=1 -> audio only, alpha=0 -> lyrics only
    Returns top `return_k` songs.
    Assumes embeddings are already L2-normalized.
    """
    # --- Fetch collections ---
    lyrics_col = client.get_collection(name=lyrics_collection_name)
    audio_col  = client.get_collection(name=audio_collection_name)

    # --- Fetch embeddings for query song ---
    lyrics_res = lyrics_col.get(ids=[song_id], include=["embeddings"])
    audio_res  = audio_col.get(ids=[song_id], include=["embeddings"])

    lyrics_emb = np.array(lyrics_res["embeddings"][0]) if len(lyrics_res.get("embeddings", [])) > 0 else None
    audio_emb  = np.array(audio_res["embeddings"][0])  if len(audio_res.get("embeddings", [])) > 0 else None

    # --- Handle missing modalities for query ---
    if lyrics_emb is None and audio_emb is None:
        raise ValueError(f"Both modalities missing for {song_id}")
    if lyrics_emb is None:
        alpha = 1.0
        query_emb = audio_emb
    elif audio_emb is None:
        alpha = 0.0
        query_emb = lyrics_emb
    else:
        query_emb = alpha * audio_emb + (1 - alpha) * lyrics_emb

    # Normalize query embedding
    q_norm = np.linalg.norm(query_emb)
    if q_norm == 0:
        raise ValueError("Query embedding has zero norm (invalid embedding)")
    query_emb = query_emb / q_norm

    # --- Fetch candidate sets ---
    lyrics_cand = lyrics_col.query(
        query_embeddings=[lyrics_emb] if lyrics_emb is not None else None,
        n_results=limit_candidates,
        include=["embeddings", "metadatas"]
    ) if lyrics_emb is not None else {"ids": [], "embeddings": [], "metadatas": []}

    audio_cand = audio_col.query(
        query_embeddings=[audio_emb] if audio_emb is not None else None,
        n_results=limit_candidates,
        include=["embeddings", "metadatas"]
    ) if audio_emb is not None else {"ids": [], "embeddings": [], "metadatas": []}

    # --- Extract lists safely ---
    lyrics_ids   = lyrics_cand["ids"][0] if len(lyrics_cand.get("ids", [])) > 0 else []
    lyrics_embs  = lyrics_cand["embeddings"][0] if len(lyrics_cand.get("embeddings", [])) > 0 else []
    lyrics_metas = lyrics_cand["metadatas"][0] if len(lyrics_cand.get("metadatas", [])) > 0 else []

    audio_ids    = audio_cand["ids"][0] if len(audio_cand.get("ids", [])) > 0 else []
    audio_embs   = audio_cand["embeddings"][0] if len(audio_cand.get("embeddings", [])) > 0 else []
    audio_metas  = audio_cand["metadatas"][0] if len(audio_cand.get("metadatas", [])) > 0 else []

    # --- Merge candidates into a unified dict ---
    cand_dict = {}

    for i, sid in enumerate(lyrics_ids):
        if sid == song_id:
            continue
        cand_dict[sid] = {
            "lyrics_emb": np.array(lyrics_embs[i]),
            "audio_emb": None,
            "lyrics_metadata": lyrics_metas[i] or {},
            "audio_metadata": {}
        }

    for i, sid in enumerate(audio_ids):
        if sid == song_id:
            continue
        if sid in cand_dict:
            cand_dict[sid]["audio_emb"] = np.array(audio_embs[i])
            cand_dict[sid]["audio_metadata"] = audio_metas[i] or {}
        else:
            cand_dict[sid] = {
                "lyrics_emb": None,
                "audio_emb": np.array(audio_embs[i]),
                "lyrics_metadata": {},
                "audio_metadata": audio_metas[i] or {}
            }

    # --- Build final merged candidate list with weighted similarity ---
    canonical_keys = ["title", "artist", "processed_at", "lyrics_preview", "duration", "num_chunks"]
    merged_candidates = []

    for sid, data in cand_dict.items():
        l_emb = data["lyrics_emb"]
        a_emb = data["audio_emb"]

        # Determine merged embedding per song
        if l_emb is None:
            merged_emb = a_emb
        elif a_emb is None:
            merged_emb = l_emb
        else:
            merged_emb = alpha * a_emb + (1 - alpha) * l_emb

        # Compute similarity
        if merged_emb is None:
            sim = -1.0
        else:
            m_norm = np.linalg.norm(merged_emb)
            if m_norm == 0:
                sim = -1.0
            else:
                merged_emb = merged_emb / m_norm
                sim = float(np.dot(query_emb, merged_emb))

        # Merge metadata
        combined = {**(data.get("audio_metadata") or {}), **(data.get("lyrics_metadata") or {})}
        canonical = {k: combined.get(k) for k in canonical_keys}
        extra = {k: v for k, v in combined.items() if k not in canonical_keys}
        if extra:
            canonical["extra_metadata"] = extra

        merged_candidates.append({
            "id": sid,
            "metadata": canonical,
            "similarity": sim
        })

    # --- Sort by similarity and return top k ---
    merged_candidates.sort(key=lambda x: x["similarity"], reverse=True)
    return merged_candidates[:return_k]

