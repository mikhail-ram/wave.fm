# JSONL helpers: read list (manifest), append atomic line (ledger), safe write
def read_jsonl(path: str) -> List[Dict]:
    if not os.path.exists(path):
        return []
    with open(path, "r", encoding="utf8") as f:
        return [json.loads(line) for line in f if line.strip()]

def append_jsonl(path: str, obj: Dict):
    # append a single JSON line and fsync to reduce chance of data loss
    with open(path, "a", encoding="utf8") as f:
        f.write(json.dumps(obj, ensure_ascii=False) + "\n")
        f.flush()
        try:
            os.fsync(f.fileno())
        except Exception:
            pass

def write_jsonl_atomic(path: str, objs: List[Dict]):
    # safely append lines to path
    with open(path, "w", encoding="utf8") as f:
        for obj in objs:
            f.write(json.dumps(obj, ensure_ascii=False) + "\n")
        f.flush()
        try:
            os.fsync(f.fileno())
        except Exception:
            pass

